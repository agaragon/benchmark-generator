import textwrap

import pytest

from featbench import deps, globs, langs
from featbench.analysis.features import _branch_name, is_fix, slugify
from featbench.analysis.quality import score_quality


@pytest.mark.parametrize("path,pattern,expected", [
    ("app/domain/user.py", "**/domain/**", True),
    ("domain/user.py", "**/domain/**", True),
    ("app/domain", "**/domain/**", True),          # bare module path from an import
    ("app/domainx/user.py", "**/domain/**", False),
    ("src/a/b.ts", "src/*/b.ts", True),
    ("src/a/c/b.ts", "src/*/b.ts", False),
    ("Src/Domain/X.java", "**/domain/**", True),    # case-insensitive
])
def test_glob_match(path, pattern, expected):
    assert globs.match(path, pattern) is expected


def test_test_and_source_classification():
    assert langs.is_test_path("tests/test_login.py")
    assert langs.is_test_path("src/login.test.ts")
    assert langs.is_test_path("pkg/login_test.go")
    assert langs.is_test_path("src/test/java/LoginServiceTest.java")
    assert not langs.is_test_path("src/login.py")
    assert langs.is_source_path("src/login.py")
    assert not langs.is_source_path("node_modules/x/index.js")


def test_generated_detection():
    assert langs.is_generated("web/dist/app.js")
    assert langs.is_generated("x/api_pb2.py")
    assert langs.is_generated("x.js", "// @generated by tool\nvar a=1;")
    assert langs.is_generated("bundle.cjs", "a" * 5000)
    assert not langs.is_generated("src/app.py", "def f():\n    return 1\n")


def test_python_imports_resolve_relative():
    text = "import os, app.domain.user\nfrom ..infra import db\nfrom . import x\n"
    imports = langs.extract_imports("app/services/billing.py", text)
    assert "app/domain/user" in imports
    assert "app/infra" in imports
    assert "app/services" in imports


def test_js_and_java_imports():
    js = "import { a } from '../domain/user';\nconst b = require('lodash');\nimport('./lazy')"
    assert langs.extract_imports("src/api/h.ts", js) == ["src/domain/user", "src/api/lazy", "lodash"] or \
        set(langs.extract_imports("src/api/h.ts", js)) == {"src/domain/user", "src/api/lazy", "lodash"}
    java = "package x;\nimport com.acme.domain.User;\nimport static com.acme.util.Strings.trim;\n"
    assert "com/acme/domain/User" in langs.extract_imports("A.java", java)


def test_python_complexity_exact():
    code = textwrap.dedent('''
        def f(a, b):
            if a and b:
                return 1
            for x in range(3):
                if x:
                    pass
            return 0

        def g():
            return [x for x in range(3) if x]
    ''')
    fns = {f.name: f for f in langs.function_metrics("m.py", code)}
    assert fns["f"].complexity == 5   # 1 + if + and + for + if
    assert fns["g"].complexity == 3   # 1 + comprehension + its if


def test_brace_language_metrics():
    code = "function a(x) {\n  if (x && y) { return 1; }\n  return 2;\n}\n"
    (fn,) = langs.function_metrics("a.js", code)
    assert fn.name == "a" and fn.complexity == 3 and fn.length == 4


def test_test_descriptions():
    assert langs.test_descriptions("t.py", "def test_login_rejects_wrong_password(): pass") == \
        ["login rejects wrong password"]
    assert langs.test_descriptions("t.ts", "it('locks after three attempts', () => {})") == \
        ["locks after three attempts"]
    assert langs.test_descriptions("x_test.go", "func TestLoginLocksAccount(t *testing.T) {}") == \
        ["login locks account"]


def test_dependency_parsing():
    assert deps.parse_manifest("requirements.txt", "requests>=2\n# c\nFlask_Login==1\n-e .\n") == {"requests", "flask-login"}
    assert deps.parse_manifest("package.json", '{"dependencies":{"a":"1"},"devDependencies":{"b":"2"}}') == {"a", "b"}
    assert deps.parse_manifest("pyproject.toml", '[project]\ndependencies=["pyyaml>=6", "rich"]\n') == {"pyyaml", "rich"}
    assert deps.parse_manifest("go.mod", "module x\nrequire (\n  github.com/a/b v1\n)\nrequire c.io/d v2\n") == \
        {"github.com/a/b", "c.io/d"}


def test_commit_heuristics():
    assert is_fix("fix(login): typo")
    assert is_fix("Hotfix crash on save")
    assert is_fix('Revert "feat: x"')
    assert not is_fix("feat(login): add login")
    assert _branch_name("Merge pull request #12 from org/feature/login") == "feature/login"
    assert _branch_name("Merge branch 'main' into feature/x") is None
    assert slugify("Account Closure!") == "account-closure"


def _metrics(**over):
    base = {"commits": 2, "lines_added": 100, "lines_deleted": 5, "files": 3, "src_files": 2, "test_files": 1,
            "fix_commits": 0, "fix_ratio": 0.0, "rework_commits": 0, "reverts": 0, "areas": ["a/b"],
            "thrash_ratio": 0.05, "largest_commit_lines": 100, "max_complexity": 4, "most_complex": "a:f",
            "long_functions": [], "layer_violations": []}
    base.update(over)
    return base


def test_quality_labels():
    assert score_quality(_metrics())["label"] == "clean"
    chaotic = score_quality(_metrics(fix_commits=4, fix_ratio=0.67, rework_commits=2, reverts=1, max_complexity=30,
                                     layer_violations=["x"], test_files=0))
    assert chaotic["label"] == "chaotic" and len(chaotic["issues"]) >= 5
    assert score_quality(_metrics(test_files=0))["label"] == "mixed"
