"""Language-aware helpers: file classification, import extraction and function metrics.

Python is analysed with `ast` (exact). Other languages use regex/brace heuristics,
which are approximate but language-agnostic enough for fitness functions.
"""

from __future__ import annotations

import ast
import posixpath
import re
from dataclasses import dataclass

LANG_BY_EXT = {
    ".py": "python",
    ".js": "javascript", ".jsx": "javascript", ".mjs": "javascript", ".cjs": "javascript",
    ".ts": "typescript", ".tsx": "typescript", ".vue": "javascript", ".svelte": "javascript",
    ".java": "java", ".kt": "kotlin", ".kts": "kotlin", ".scala": "scala",
    ".go": "go", ".cs": "csharp", ".rs": "rust", ".rb": "ruby", ".php": "php",
    ".swift": "swift", ".pl": "perl", ".pm": "perl", ".t": "perl", ".c": "c", ".h": "c", ".cpp": "cpp", ".cc": "cpp", ".hpp": "cpp",
}

FRONTEND_EXTS = {".jsx", ".tsx", ".vue", ".svelte", ".css", ".scss", ".html"}

IGNORED_DIRS = {"node_modules", "vendor", "third_party", "dist", "build", ".venv", "venv",
                "__pycache__", "target", ".git", "coverage", ".next", "out"}

_TEST_PATTERNS = [
    re.compile(r"(^|/)(tests?|__tests__|specs?|test_?suite|testcases?|testing|e2e|integration_tests?)/", re.I),
    re.compile(r"\.t$"),
    re.compile(r"(^|/)test_[^/]+\.py$"),
    re.compile(r"_test\.(py|go|rb|exs?)$"),
    re.compile(r"\.(test|spec)\.[jt]sx?$"),
    re.compile(r"(Test|Tests|IT|Spec)\.(java|kt|cs|scala|swift|php)$"),
    re.compile(r"_spec\.rb$"),
    re.compile(r"(^|/)conftest\.py$"),
]
_PERF_PATTERN = re.compile(r"(^|/|_|-)(bench|benchmarks?|perf|performance|load|locust|k6|stress)(/|_|-|\.)", re.I)


def language_of(path: str) -> str | None:
    return LANG_BY_EXT.get(posixpath.splitext(path)[1].lower())


def is_ignored(path: str) -> bool:
    return any(part in IGNORED_DIRS for part in path.split("/"))


def is_test_path(path: str) -> bool:
    return any(p.search(path) for p in _TEST_PATTERNS)


def is_perf_path(path: str) -> bool:
    return bool(_PERF_PATTERN.search(path)) and language_of(path) is not None


_GENERATED_PATH = re.compile(r"(\.min\.|\.bundle\.|(^|/)(dist|build|generated|gen|vendor|out)/|_pb2\.py$|\.pb\.go$|\.g\.dart$|\.designer\.cs$)", re.I)
_GENERATED_MARK = re.compile(r"@generated|do not edit|auto-?generated|code generated by", re.I)


def is_generated(path: str, text: str | None = None) -> bool:
    """Bundles, minified and generated code must not be judged as hand-written code."""
    if _GENERATED_PATH.search(path):
        return True
    if text:
        head = "\n".join(text.splitlines()[:5])
        if _GENERATED_MARK.search(head):
            return True
        lines = text.splitlines() or [""]
        if max(len(l) for l in lines) > 2000 or len(text) / len(lines) > 300:
            return True
    return False


_LOCKFILES = {"package-lock.json", "yarn.lock", "pnpm-lock.yaml", "poetry.lock", "Cargo.lock", "go.sum",
              "composer.lock", "Gemfile.lock", "Pipfile.lock", "uv.lock", "bun.lockb", "bun.lock"}


def is_noise(path: str) -> bool:
    """Files whose line counts say nothing about the size of a change (lockfiles, generated code)."""
    return posixpath.basename(path) in _LOCKFILES or is_generated(path) or is_ignored(path)


def is_source_path(path: str) -> bool:
    return language_of(path) is not None and not is_ignored(path) and not is_test_path(path)


# --------------------------------------------------------------------------- imports

_PY_IMPORT = re.compile(r"^\s*import\s+([\w.]+(?:\s*,\s*[\w.]+)*)", re.M)
_PY_FROM = re.compile(r"^\s*from\s+(\.*[\w.]*)\s+import\b", re.M)
_JS_IMPORT = re.compile(r"""(?:import|export)\s[^'"]*?from\s*['"]([^'"]+)['"]|import\s*\(?\s*['"]([^'"]+)['"]|require\(\s*['"]([^'"]+)['"]\s*\)""")
_JAVA_IMPORT = re.compile(r"^\s*import\s+(?:static\s+)?([\w.]+)", re.M)
_GO_IMPORT_BLOCK = re.compile(r"import\s*\(([^)]*)\)", re.S)
_GO_IMPORT_SINGLE = re.compile(r'^\s*import\s+(?:\w+\s+)?"([^"]+)"', re.M)
_CS_USING = re.compile(r"^\s*using\s+(?:static\s+)?([\w.]+)\s*;", re.M)
_RUST_USE = re.compile(r"^\s*(?:pub\s+)?use\s+([\w:]+)", re.M)
_PHP_USE = re.compile(r"^\s*use\s+([\w\\]+)", re.M)
_RUBY_REQ = re.compile(r"""^\s*require(?:_relative)?\s+['"]([^'"]+)['"]""", re.M)


def extract_imports(path: str, text: str) -> list[str]:
    """Return imported targets as slash-separated 'module paths' (resolved when relative)."""
    lang = language_of(path)
    here = posixpath.dirname(path)
    out: list[str] = []
    if lang == "python":
        for m in _PY_IMPORT.finditer(text):
            out += [x.strip().replace(".", "/") for x in m.group(1).split(",")]
        for m in _PY_FROM.finditer(text):
            mod = m.group(1)
            level = len(mod) - len(mod.lstrip("."))
            name = mod.lstrip(".").replace(".", "/")
            if level:
                base = here
                for _ in range(level - 1):
                    base = posixpath.dirname(base)
                out.append(posixpath.join(base, name) if name else base)
            else:
                out.append(name)
    elif lang in ("javascript", "typescript"):
        for m in _JS_IMPORT.finditer(text):
            spec = next(g for g in m.groups() if g)
            if spec.startswith("."):
                spec = posixpath.normpath(posixpath.join(here, spec))
            out.append(spec)
    elif lang in ("java", "kotlin", "scala"):
        out += [m.group(1).replace(".", "/") for m in _JAVA_IMPORT.finditer(text)]
    elif lang == "go":
        for block in _GO_IMPORT_BLOCK.findall(text):
            out += re.findall(r'"([^"]+)"', block)
        out += _GO_IMPORT_SINGLE.findall(text)
    elif lang == "csharp":
        out += [m.replace(".", "/") for m in _CS_USING.findall(text)]
    elif lang == "rust":
        out += [m.replace("::", "/") for m in _RUST_USE.findall(text)]
    elif lang == "php":
        out += [m.replace("\\", "/") for m in _PHP_USE.findall(text)]
    elif lang == "ruby":
        out += _RUBY_REQ.findall(text)
    return [o for o in out if o]


# --------------------------------------------------------------------------- function metrics

@dataclass
class FunctionMetric:
    name: str
    start: int
    end: int
    complexity: int

    @property
    def length(self) -> int:
        return self.end - self.start + 1


class _PyComplexity(ast.NodeVisitor):
    def __init__(self) -> None:
        self.value = 1

    def generic_visit(self, node):
        if isinstance(node, (ast.If, ast.For, ast.AsyncFor, ast.While, ast.IfExp,
                             ast.ExceptHandler, ast.Assert, ast.comprehension)):
            self.value += 1
            if isinstance(node, ast.comprehension):
                self.value += len(node.ifs)
        elif isinstance(node, ast.BoolOp):
            self.value += len(node.values) - 1
        elif isinstance(node, ast.match_case):
            self.value += 1
        super().generic_visit(node)

    def visit_FunctionDef(self, node):  # nested functions are measured on their own
        pass

    visit_AsyncFunctionDef = visit_FunctionDef
    visit_Lambda = visit_FunctionDef


def _python_functions(text: str) -> list[FunctionMetric]:
    tree = ast.parse(text)
    result = []
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            v = _PyComplexity()
            for child in node.body:
                v.visit(child)
            result.append(FunctionMetric(node.name, node.lineno, node.end_lineno or node.lineno, v.value))
    return result


_KEYWORDS = {"if", "for", "while", "switch", "catch", "return", "else", "do", "try", "new",
             "function", "synchronized", "using", "foreach", "lock", "when", "match", "loop"}
_FUNC_HEADERS = {
    "javascript": [r"function\s*\*?\s*(\w+)\s*\(", r"(\w+)\s*[:=]\s*(?:async\s*)?(?:function\s*)?\([^)]*\)\s*(?:=>)?\s*\{",
                   r"^\s*(?:static\s+|async\s+|public\s+|private\s+|protected\s+|get\s+|set\s+)*(\w+)\s*\([^)]*\)\s*(?::\s*[\w<>\[\]|, .]+)?\s*\{"],
    "java": [r"^\s*(?:[\w<>\[\],?@]+\s+)+(\w+)\s*\([^;]*\)\s*(?:throws\s+[\w., ]+)?\s*\{"],
    "kotlin": [r"\bfun\s+(?:<[^>]+>\s*)?(?:[\w.]+\.)?(\w+)\s*\("],
    "go": [r"^func\s+(?:\([^)]*\)\s*)?(\w+)\s*\("],
    "rust": [r"\bfn\s+(\w+)"],
    "swift": [r"\bfunc\s+(\w+)"],
    "php": [r"\bfunction\s+(\w+)\s*\("],
}
_FUNC_HEADERS["typescript"] = _FUNC_HEADERS["javascript"]
for _l in ("csharp", "scala", "c", "cpp"):
    _FUNC_HEADERS[_l] = _FUNC_HEADERS["java"]
_DECISIONS = re.compile(r"\b(if|for|foreach|while|case|catch|elif|except|when)\b|&&|\|\||\s\?\s")


def _brace_functions(text: str, lang: str) -> list[FunctionMetric]:
    headers = [re.compile(p, re.M) for p in _FUNC_HEADERS.get(lang, [])]
    if not headers:
        return []
    result: list[FunctionMetric] = []
    taken: set[int] = set()
    line_starts = [0] + [i + 1 for i, ch in enumerate(text) if ch == "\n"]

    def line_of(idx: int) -> int:
        lo, hi = 0, len(line_starts) - 1
        while lo < hi:
            mid = (lo + hi + 1) // 2
            if line_starts[mid] <= idx:
                lo = mid
            else:
                hi = mid - 1
        return lo + 1

    for rx in headers:
        for m in rx.finditer(text):
            name = m.group(1)
            if name in _KEYWORDS:
                continue
            brace = text.find("{", m.end() - 1)
            if brace == -1 or text[m.end():brace].count(";") or brace - m.end() > 200:
                continue
            start_line = line_of(m.start())
            if start_line in taken:
                continue
            depth, i = 0, brace
            while i < len(text):
                if text[i] == "{":
                    depth += 1
                elif text[i] == "}":
                    depth -= 1
                    if depth == 0:
                        break
                i += 1
            body = text[brace:i]
            taken.add(start_line)
            result.append(FunctionMetric(name, start_line, line_of(i), 1 + len(_DECISIONS.findall(body))))
    return result


def function_metrics(path: str, text: str) -> list[FunctionMetric]:
    if is_generated(path, text):
        return []
    lang = language_of(path)
    if lang == "python":
        try:
            return _python_functions(text)
        except (SyntaxError, ValueError):
            return []
    if lang:
        return _brace_functions(text, lang)
    return []


# --------------------------------------------------------------------------- test names -> business rules

_PY_TEST = re.compile(r"^\s*(?:async\s+)?def\s+(test_\w+)", re.M)
_JS_TEST = re.compile(r"""\b(?:it|test|describe)\s*\(\s*(['"`])(.+?)\1""")
_GO_TEST = re.compile(r"^func\s+(Test\w+)\s*\(", re.M)
_JAVA_TEST = re.compile(r"@Test[^\n]*\n(?:\s*@[\w.()=\" ]+\n)*\s*(?:public\s+|private\s+|internal\s+)?(?:void|fun)\s+`?([\w ]+?)`?\s*\(")
_DISPLAY = re.compile(r"""@DisplayName\(\s*"([^"]+)"\s*\)""")
_RUBY_TEST = re.compile(r"""\b(?:it|describe|context)\s+['"](.+?)['"]""")


def _humanize(name: str) -> str:
    name = re.sub(r"^(test_?|Test)", "", name)
    name = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", " ", name)
    return name.replace("_", " ").strip().lower()


def test_descriptions(path: str, text: str) -> list[str]:
    """Human-readable behaviours derived from test names (used to describe business rules)."""
    lang = language_of(path)
    if lang == "python":
        return [_humanize(n) for n in _PY_TEST.findall(text)]
    if lang in ("javascript", "typescript"):
        return [m.group(2) for m in _JS_TEST.finditer(text)]
    if lang == "go":
        return [_humanize(n) for n in _GO_TEST.findall(text)]
    if lang in ("java", "kotlin", "csharp", "scala"):
        named = _DISPLAY.findall(text)
        return named or [_humanize(n) for n in _JAVA_TEST.findall(text)]
    if lang == "ruby":
        return _RUBY_TEST.findall(text)
    return []
